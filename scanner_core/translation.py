IS_WINDOWS = platform.system() == "Windows"

# The OBD port selector is worded around Windows COM ports by default. On
# Linux/macOS the same dropdown holds device paths (/dev/ttyUSB0, /dev/rfcomm0,
# ...), so every user-facing string gets reworded once here instead of
# keeping separate "COM port" / "adapter port" copies of each string.
_PORT_WORDING_REPLACEMENTS = [
    ("USB / COM Adapter Port", "USB / Serial Adapter Port"),
    ("USB / COM Adapterpoort", "USB / Seriële Adapterpoort"),
    ("Adapter COM port", "Adapter port"),
    ("Adapter COM-poort", "Adapter poort"),
    ("do not force a COM port.", "do not force an adapter port."),
    ("Auto / COM5", "Auto / /dev/ttyUSB0"),
    ("Detected COM Ports", "Detected Adapter Ports"),
    ("Gedetecteerde COM-poorten", "Gedetecteerde adapterpoorten"),
    ("COM ports", "adapter ports"),
    ("COM-poorten", "adapterpoorten"),
    ("COM port", "adapter port"),
    ("COM-poort", "adapterpoort"),
    ("COM selection", "adapter selection"),
    ("COM-selectie", "adapter-selectie"),
    ("COM configuration", "adapter configuration"),
    ("COM-configuratie", "adapterconfiguratie"),
]


def _reword_port_text(text):
    if IS_WINDOWS or not isinstance(text, str) or "COM" not in text:
        return text

    result = text
    for old, new in _PORT_WORDING_REPLACEMENTS:
        result = result.replace(old, new)

    if result and text[0].isupper() and result[0].islower():
        result = result[0].upper() + result[1:]

    return result


def _reword_ports(value):
    if IS_WINDOWS:
        return value
    if isinstance(value, str):
        return _reword_port_text(value)
    if isinstance(value, list):
        return [_reword_ports(item) for item in value]
    if isinstance(value, tuple):
        return tuple(_reword_ports(item) for item in value)
    if isinstance(value, dict):
        return {key: _reword_ports(item) for key, item in value.items()}
    return value


