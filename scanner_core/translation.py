def _deep_merge(base: dict, overrides: dict) -> dict:
    merged = deepcopy(base)
    for key, value in overrides.items():
        if isinstance(value, dict) and isinstance(merged.get(key), dict):
            merged[key] = _deep_merge(merged[key], value)
        else:
            merged[key] = deepcopy(value)
    return merged


def _resolve_key(data: dict, key: str):
    current = data
    for part in key.split("."):
        if not isinstance(current, dict) or part not in current:
            return None
        current = current[part]
    return current


def get_language(requested: str | None) -> str:
    code = str(requested or DEFAULT_LANGUAGE).strip().lower()
    return code if code in SUPPORTED_LANGUAGE_CODES else DEFAULT_LANGUAGE


def get_units(requested: str | None) -> str:
    code = str(requested or DEFAULT_UNITS).strip().lower()
    return code if code in SUPPORTED_UNIT_CODES else DEFAULT_UNITS


def get_theme(requested: str | None) -> str:
    code = str(requested or DEFAULT_THEME).strip().lower()
    return code if code in SUPPORTED_THEME_CODES else DEFAULT_THEME


def get_translations(lang: str) -> dict:
    code = get_language(lang)
    base = TRANSLATIONS["en"]
    merged = deepcopy(base) if code == "en" else _deep_merge(base, TRANSLATIONS.get(code, {}))
    return _reword_ports(merged)


def translate(lang: str, key: str, **kwargs):
    data = get_translations(lang)
    value = _resolve_key(data, key)
    if value is None:
        return key
    if isinstance(value, str) and kwargs:
        try:
            return value.format(**kwargs)
        except Exception:
            return value
    return value


def localize_text(value, lang: str | None):
    """Translate one server-generated string.

    Server text is produced in English by the Python side and translated here
    on the way out, for every supported language - not only Dutch, which used
    to leave a German, Spanish or Polish dashboard mixing a translated
    interface with English status messages.

    Three kinds of string are handled, in order of specificity: an exact
    match, a sentence with a runtime value in the middle (a voltage, a
    temperature), and a translatable prefix followed by data that must be
    passed through untouched. Anything unknown is returned as-is, so a new
    message shows up in English rather than breaking the page.
    """
    code = get_language(lang)
    if code == DEFAULT_LANGUAGE or not isinstance(value, str) or not value:
        return value

    exact = SERVER_TEXT_BY_LANGUAGE.get(code)
    if not exact:
        return value

    translated = exact.get(value)
    if translated:
        return translated

    for (prefix, suffix), (target_prefix, target_suffix) in SERVER_PATTERNS_BY_LANGUAGE.get(code, {}).items():
        if value.startswith(prefix) and value.endswith(suffix) and len(value) > len(prefix) + len(suffix) - 1:
            middle = value[len(prefix):len(value) - len(suffix)]
            return f"{target_prefix}{middle}{target_suffix}"

    for source_prefix, target_prefix in SERVER_PREFIX_BY_LANGUAGE.get(code, {}).items():
        if value.startswith(source_prefix):
            return target_prefix + value[len(source_prefix):]

    return value


def localize_payload(value, lang: str | None):
    if isinstance(value, str):
        return _reword_port_text(localize_text(value, lang))
    if isinstance(value, list):
        return [localize_payload(item, lang) for item in value]
    if isinstance(value, tuple):
        return tuple(localize_payload(item, lang) for item in value)
    if isinstance(value, dict):
        return {key: localize_payload(item, lang) for key, item in value.items()}
    return value










